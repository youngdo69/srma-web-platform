# Offline Web overlay release gate, no Job/DB modifications and no AI calls.
stopifnot(requireNamespace("jsonlite",quietly=TRUE),requireNamespace("digest",quietly=TRUE))
run_overlay_test <- function() {
source("web/R/service.R",local=TRUE)
root <- tempfile("srma-release-test-");dir.create(root,recursive=TRUE)
on.exit(unlink(root,recursive=TRUE),add=TRUE)
dirs<-c("web/docs","web/adapter","web/R","web/ui","R")
for(d in dirs)dir.create(file.path(root,d),recursive=TRUE,showWarnings=FALSE)
writeLines("baseline",file.path(root,"R/scientific.R"))
writeLines("old1",file.path(root,"web/adapter/evidence.R"))
writeLines("old2",file.path(root,"web/R/evidence.R"))
writeLines("old3",file.path(root,"web/ui/evidence.R"))
writeLines("old4",file.path(root,"web/R/service.R"))
sha<-function(p)digest::digest(file=file.path(root,p),algo="sha256")
paths<-c("R/scientific.R","web/adapter/evidence.R","web/R/evidence.R","web/ui/evidence.R","web/R/service.R")
manifest<-setNames(as.list(vapply(paths,sha,character(1))),paths)
stopifnot("web/R/service.R" %in% names(manifest), !("web/R/adapter.R" %in% names(manifest)))
jsonlite::write_json(manifest,file.path(root,"web/docs/engine-source-manifest.json"),auto_unbox=TRUE,pretty=TRUE)
jsonlite::write_json(list(commit="test"),file.path(root,"web/docs/engine-baseline.json"),auto_unbox=TRUE)
basepath<-file.path(root,"web/docs/engine-source-manifest.json")
basehash<-digest::digest(file=basepath,algo="sha256")
for(p in setdiff(paths[-1L],"web/R/service.R"))writeLines(paste("new",p),file.path(root,p))
file.copy("web/R/service.R",file.path(root,"web/R/service.R"),overwrite=TRUE)
file.copy("web/R/adapter.R",file.path(root,"web/R/adapter.R"),overwrite=TRUE)
file.copy("web/adapter/pdf_results.R",file.path(root,"web/adapter/pdf_results.R"),overwrite=TRUE)
overlay_paths<-c(paths[-1L],"web/R/adapter.R","web/adapter/pdf_results.R")
release<-list(schema_version="SRMA_WEB_DEV_OVERLAY_V1",release_label="RC28.19_PDF_DISCOVERY_SIMPLE_UI",base_manifest_sha256=basehash,files=setNames(as.list(vapply(overlay_paths,sha,character(1))),overlay_paths))
overlaypath<-file.path(root,"web/docs/approved-web-overlay.json")
jsonlite::write_json(release,overlaypath,auto_unbox=TRUE,pretty=TRUE)
web_assert<-function(ok,msg,code="SYSTEM_FAILED")if(!isTRUE(ok))stop(msg)
web_sha<-function(p)digest::digest(file=p,algo="sha256")
web_json<-function(x)jsonlite::toJSON(x,auto_unbox=TRUE,null="null",na="null",dataframe="rows")
web_now<-function()"2026-10-18T00:00:00Z"
web_query<-function(...)data.frame(id="already-registered")
web_exec<-function(...)stop("DB must not be modified by this test")
settings<-list(engine_root=root,mode="development")
baseid<-paste0("snapshot-",substr(digest::digest(as.character(web_json(manifest)),algo="sha256",serialize=FALSE),1L,16L))
stopifnot(identical(web_register_engine(NULL,settings),baseid))
expect_fail<-function(expr){ok<-tryCatch({force(expr);FALSE},error=function(e)TRUE);stopifnot(ok)}
# Wrong Web SHA, wrong scientific SHA, overlay missing, production overlay,
# baseline-manifest modification all FAIL CLOSED.
webfile<-file.path(root,"web/ui/evidence.R");writeLines("tampered",webfile)
expect_fail(web_register_engine(NULL,settings));writeLines("new web/ui/evidence.R",webfile)
sci<-file.path(root,"R/scientific.R");writeLines("tampered",sci)
expect_fail(web_register_engine(NULL,settings));writeLines("baseline",sci)
stopifnot(identical(web_register_engine(NULL,settings),baseid))
# In the real 107-entry manifest service.R itself is pinned. Tampering
# with it must fail even though it also supplies the registration code.
service_path<-file.path(root,"web/R/service.R")
service_content<-readBin(service_path,"raw",n=file.info(service_path)$size)
writeLines("tampered-service",service_path)
expect_fail(web_register_engine(NULL,settings))
writeBin(service_content,service_path)
stopifnot(identical(web_register_engine(NULL,settings),baseid))
settings$mode<-"production";expect_fail(web_register_engine(NULL,settings));settings$mode<-"development"
file.rename(overlaypath,paste0(overlaypath,".bak"));expect_fail(web_register_engine(NULL,settings));file.rename(paste0(overlaypath,".bak"),overlaypath)
write(" ",file=basepath,append=TRUE);expect_fail(web_register_engine(NULL,settings))
cat("PASS: RC28.19 PDF discovery overlay strict SHA and unchanged scientific engine ID\n")
}
run_overlay_test()
