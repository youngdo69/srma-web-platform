# Operator-only real provider acceptance against an already Human-approved manuscript plan.
source("web/load.R")
s<-web_settings();s<-web_science_settings(s);con<-web_db(s)
web_migrate(con,s)
actor<-Sys.getenv("SRMA_ACCEPTANCE_ACTOR");project<-Sys.getenv("SRMA_ACCEPTANCE_PROJECT");version<-Sys.getenv("SRMA_ACCEPTANCE_MANUSCRIPT_VERSION")
web_assert(all(nzchar(c(actor,project,version))),"Supply operator acceptance actor/project/draft version.")
web_assert(nzchar(Sys.getenv("OPENAI_API_KEY")),"Real provider credential required.","PROVIDER_UNAVAILABLE")
v<-web_c2_prepare_ai(con,s,actor,project,version,"Introduction")
j<-web_submit(con,s,actor,v$project_id,v$version_id,"generate_manuscript_section");web_worker_once(con,s)
row<-web_query(con,"SELECT state FROM jobs WHERE id=?j",j=j);web_assert(row$state=="COMPLETE","Real manuscript provider job did not complete.")
v<-web_c2_accept(con,s,actor,v$project_id,v$version_id,j)
stopifnot(web_c2_view(con,s,actor,v$project_id,v$version_id)$sections$Introduction$source=="AI")
cat("Real provider draft saved; Human review remains required. Version:",v$version_id,"\n")
DBI::dbDisconnect(con)
