source("web/load.R")

root <- tempfile("srma-delete-test-")
dir.create(root, recursive = TRUE)
settings <- web_settings(engine_root = getwd(), data_root = root, backend = "sqlite")
con <- web_db(settings)
on.exit({try(DBI::dbDisconnect(con), silent = TRUE); unlink(root, recursive = TRUE, force = TRUE)}, add = TRUE)
web_migrate(con, settings)

web_exec(con, "INSERT INTO app_users(id,display_name) VALUES('u1','User One')")
web_exec(con, "INSERT INTO workspaces(id,name) VALUES('w1','Workspace One')")
web_exec(con, "INSERT INTO workspace_members(workspace_id,user_id) VALUES('w1','u1')")
web_exec(con, "INSERT INTO projects(id,workspace_id,canonical_id,title,created_at) VALUES('p1','w1','review-delete-test','Delete test review',?n)", n = web_now())

stopifnot(nrow(web_authorize(con, "u1", "p1")) == 1L)
result <- web_delete_project(con, "u1", "p1", "DELETE")
stopifnot(isTRUE(result$deleted))
row <- web_query(con, "SELECT deleted_at,deleted_by FROM projects WHERE id='p1'")
stopifnot(nrow(row) == 1L, !is.na(row$deleted_at[[1L]]), nzchar(row$deleted_at[[1L]]), identical(row$deleted_by[[1L]], "u1"))
audit <- web_query(con, "SELECT event_type FROM audit_events WHERE project_id='p1' AND event_type='PROJECT_DELETED'")
stopifnot(nrow(audit) == 1L)
blocked <- tryCatch({web_authorize(con, "u1", "p1"); FALSE}, error = function(e) TRUE)
stopifnot(blocked)
cat("PASS: review soft-delete preserves audit history and removes normal project access.\n")
