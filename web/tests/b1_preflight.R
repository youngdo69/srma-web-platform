# Requires the separately verified canonical R/library configured by the operator.
source("web/tests/b1_import.R")
con<-web_db(settings)
Sys.setenv(SRMA_WEB_TEST_IDP="1")
DBI::dbExecute(con,"INSERT INTO external_identities VALUES('local-test','preflight','local-researcher')")
p<-web_test_provider("preflight");session_token<-web_sign_in(con,p$provider,p$credential)
request<-function(action,args)web_request(con,session_token,action,args,"nonce","nonce",settings)
job<-request("submit",list(project_id=v2$project_id,version_id=v2$version_id,operation="validate_database_inputs"))
web_worker_once(con,settings)
j<-web_query(con,"SELECT * FROM jobs WHERE id=?id",id=job)
if(j$state!="USER_ACTION_REQUIRED")print(web_parse(j$result_json))
stopifnot(j$state=="USER_ACTION_REQUIRED")
a<-web_query(con,"SELECT * FROM artifacts WHERE job_id=?j",j=job);stopifnot(nrow(a)==2L)
report<-tempfile();request("download",list(project_id=v2$project_id,artifact_id=a$id[1],destination=report));stopifnot(web_sha(report)==a$checksum[1])
cat("PASS: authenticated persistent preflight uses canonical R 4.6.1; missing CENTRAL produces action-required state and downloadable evidence\n")
v3<-web_upload_database(con,settings,"local-researcher",v2$project_id,v2$version_id,"central",upload,upload_root)
job2<-request("submit",list(project_id=v3$project_id,version_id=v3$version_id,operation="validate_database_inputs"))
web_worker_once(con,settings)
j2<-web_query(con,"SELECT * FROM jobs WHERE id=?id",id=job2)
if(j2$state!="COMPLETE")print(web_parse(j2$result_json))
stopifnot(j2$state=="COMPLETE",j2$attempts==1L)
a2<-web_query(con,"SELECT * FROM artifacts WHERE job_id=?j",j=job2);stopifnot(nrow(a2)==2L,all(a2$approval_state=="UNREVIEWED"))
stopifnot(all(DBI::dbGetQuery(con,"SELECT DISTINCT operation FROM jobs")$operation=="validate_database_inputs"),
 all(web_query(con,"SELECT status FROM gates WHERE version_id=?v",v=v3$version_id)$status=="PENDING"))
summary <- request("database_status",list(project_id=v3$project_id,version_id=v3$version_id))
stopifnot(nrow(summary)==2L,all(summary$Validation=="READY"),!any(grepl("path|file|locator",names(summary))))
r<-web_parse(j2$result_json)
stopifnot(grepl("4.6.1",r$provenance$R))
evidence<-list(test_inputs="Explicitly synthetic RIS parser fixtures; no real studies or clinical observations",databases=c("embase","central"),
 first_state=j$state,complete_state=j2$state,attempts=j2$attempts,artifacts=a2[,c("logical_name","checksum","approval_state")],
 provenance=r$provenance,no_downstream_operation=TRUE,human_approvals_unchanged=TRUE)
jsonlite::write_json(evidence,"web/evidence/b1/preflight-real-engine.json",pretty=TRUE,auto_unbox=TRUE,dataframe="rows")
DBI::dbDisconnect(con)
cat("PASS: both manual inputs validated by canonical gate; COMPLETE with two registered artifacts; no human approval or downstream operation\n")
